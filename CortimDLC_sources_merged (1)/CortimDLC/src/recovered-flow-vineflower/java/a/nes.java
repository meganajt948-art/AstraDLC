package a;

final class nes {
   final pzc net;
   final int neu;
   final boolean nev;

   nes(pzc area, int diamonds, boolean look) {
      this.net = area;
      this.neu = diamonds;
      this.nev = look;
   }

   public pzc area() {
      return this.net;
   }

   public int diamonds() {
      return this.neu;
   }

   public boolean look() {
      return this.nev;
   }
}
