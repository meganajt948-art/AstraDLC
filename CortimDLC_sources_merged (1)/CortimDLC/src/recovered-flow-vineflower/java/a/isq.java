package a;

record isq(uok texture, long frame) {
   private final uok isr;
   private final long iss;

   private isq(uok texture, long frame) {
      this.isr = texture;
      this.iss = frame;
   }

   public uok texture() {
      return this.isr;
   }

   public long frame() {
      return this.iss;
   }
}
