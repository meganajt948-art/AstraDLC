package a;

final class tnc {
   final sze tnd;
   final int tne;
   final int tnf;

   tnc(sze seg, int k0, int limit) {
      this.tnd = seg;
      this.tne = k0;
      this.tnf = limit;
   }

   public sze seg() {
      return this.tnd;
   }

   public int k0() {
      return this.tne;
   }

   public int limit() {
      return this.tnf;
   }
}
