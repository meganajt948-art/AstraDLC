package a;

final class eqw {
   final int[] eqx;
   final int eqy;
   final int eqz;

   eqw(int[] px, int w, int h) {
      this.eqx = px;
      this.eqy = w;
      this.eqz = h;
   }

   public int[] px() {
      return this.eqx;
   }

   public int w() {
      return this.eqy;
   }

   public int h() {
      return this.eqz;
   }
}
