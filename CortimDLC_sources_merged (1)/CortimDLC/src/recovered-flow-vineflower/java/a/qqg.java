package a;

public final class qqg {
   private final qqp qqh;
   private final int qqi;
   private final qqm qqj;

   public qqg(qqp kind, int id, qqm entry) {
      this.qqh = kind;
      this.qqi = id;
      this.qqj = entry;
   }

   public qqp kind() {
      return this.qqh;
   }

   public int id() {
      return this.qqi;
   }

   public qqm entry() {
      return this.qqj;
   }
}
